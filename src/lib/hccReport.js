/**
 * Defective-device report (HCC, devices not owned by the hospital).
 *
 * Only the report's DATA is stored (device.report): the parts and failures
 * the admin picked, the findings text, the recommendation, who issued it and
 * when. The printable page / PDF is rebuilt from that data on request, so no
 * files pile up in storage.
 *
 * The wording and which sections appear come from an admin-editable template;
 * the layout itself is fixed.
 */

export const DEFAULT_TEMPLATE = {
  title: "Home Care Device — Defective Device Report",
  headerAr: "وزارة الحرس الوطني — الشؤون الصحية",
  headerEn: "Ministry of National Guard — Health Affairs",
  headerSub: "Healthcare Technology Management Services · HTMS-Cardiac · KAMC-Riyadh",
  ownershipNote: "Device not owned by MNGHA Health Affairs — this report is issued for the Bed Management Department.",
  findingsTemplate:
    "The {device_type} ({manufacturer} {model}, serial {serial}) was found defective on inspection. " +
    "Faulty parts: {parts}. The device is not safe for continued patient use.",
  footerNote: "Generated by the HTMS-Cardiac Platform · Contains confidential patient information",
  showPatient: true,
  showChecklist: true,
  showRecommendation: true,
};

/** Placeholders the admin can use in the findings text. */
export const PLACEHOLDERS = ["{device_type}", "{manufacturer}", "{model}", "{serial}", "{device_no}", "{parts}"];

export const withDefaults = (t) => ({ ...DEFAULT_TEMPLATE, ...(t || {}) });

/** "Blower Motor (Does not power on); Main Board (Error code displayed)" */
export const partsSummary = (parts = []) =>
  parts.filter(p => p.part).map(p => p.failure ? `${p.part} (${p.failure})` : p.part).join("; ");

/** Fill the findings template for one device. */
export function findingsFor(template, device, parts) {
  const t = withDefaults(template).findingsTemplate;
  const val = {
    "{device_type}": device.deviceType || "device",
    "{manufacturer}": device.manufacturer || "—",
    "{model}": device.model || "—",
    "{serial}": device.htmSn || "—",
    "{device_no}": device.deviceNo || "—",
    "{parts}": partsSummary(parts) || "—",
  };
  return t.replace(/\{(device_type|manufacturer|model|serial|device_no|parts)\}/g, m => val[m]);
}

const esc = (s) => String(s ?? "").replace(/&/g, "&amp;").replace(/</g, "&lt;").replace(/>/g, "&gt;").replace(/"/g, "&quot;");
const fmtDate = (iso, time = true) => {
  if (!iso) return "—";
  return new Date(iso).toLocaleString("en-GB", {
    day: "2-digit", month: "short", year: "numeric",
    ...(time ? { hour: "2-digit", minute: "2-digit", hour12: true } : {}),
  });
};

/** One checklist answer as display text + pass/fail/neutral. */
function answerOf(step, a) {
  if (!a) return { text: "—", cls: "" };
  if (step.type === "pass_fail" || step.type === "pass_fail_na") {
    return a.value === "pass" ? { text: "✓ Pass", cls: "ok" }
         : a.value === "fail" ? { text: "✗ Fail", cls: "bad" } : { text: "N/A", cls: "" };
  }
  if (step.type === "number_range") {
    const v = Number(a.value);
    const lo = step.min === "" || step.min == null ? -Infinity : Number(step.min);
    const hi = step.max === "" || step.max == null ? Infinity : Number(step.max);
    const ok = !isNaN(v) && v >= lo && v <= hi;
    return { text: `${a.value}${step.unit ? " " + step.unit : ""}`, cls: ok ? "ok" : "bad" };
  }
  if (step.type === "select" && step.scored) {
    return { text: String(a.value ?? "—"), cls: (step.passOptions || []).includes(a.value) ? "ok" : "bad" };
  }
  return { text: `${a.value ?? "—"}${step.unit ? " " + step.unit : ""}`, cls: "" };
}

